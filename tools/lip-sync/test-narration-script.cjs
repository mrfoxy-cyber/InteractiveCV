const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = process.argv[2] || path.join(__dirname,'../../dist/character-map');
const {match} = require(path.join(root,'narration-script-match.js'));
const script = JSON.parse(fs.readFileSync(path.join(root,'narration-scripts.json'),'utf8'));
const recordings = JSON.parse(fs.readFileSync(path.join(root,'narration-recordings.json'),'utf8'));
for (const file of recordings.files) assert.ok(match(script,file), 'Missing transcript: '+file);
assert.equal(match(script,'education-skövde.mp3').file,'education-skovde.mp3');
assert.equal(match(script,'goatly.mp3').file,'project-goatly.mp3');
assert.equal(match(script,'mental-model-graph.mp3').file,'project-mmg.mp3');
assert.equal(match(script,'frog-game.mp3').file,'project-frog.mp3');
assert.equal(match(script,'komvux.wav').file,'education-komvux.mp3');
assert.equal(match(script,'gymnasium.mp3').file,'education-gymnasium.mp3');
assert.equal(match(script,'unknown.mp3'),null);
assert.equal(match(null,'welcome.mp3'),null);
assert.ok(!match(script,'welcome.mp3').text.includes('Use the listen button when'));
assert.ok(!match(script,'languages.mp3').text.includes('Reusable navigation prompts'));
assert.equal(match(script,'WELCOME.MP3').file,'welcome.mp3');
console.log(`${recordings.files.length} narration scripts matched; Unicode, renamed files, unknown-file rejection and saved ODT text passed.`);
